"use client";

import { ArrowLeft, CheckCircle2, CircleAlert } from "lucide-react";
import Link from "next/link";
import { useParams } from "next/navigation";
import { useEffect, useState } from "react";

import { PageHeader } from "@/components/app-shell";
import { AuthGate } from "@/components/auth-gate";
import {
  ArtifactButtons,
  EmptyState,
  PreviewTable,
  StatTile,
} from "@/components/product-console";
import type { ArtifactList, DocumentPreview, GenerationRun, TablePreview } from "@/lib/api";
import { getDocumentPreview, getRun, getRunArtifacts, getTablePreview } from "@/lib/api";

export default function RunDetailPage() {
  return (
    <AuthGate>
      {() => <RunDetailContent />}
    </AuthGate>
  );
}

function RunDetailContent() {
  const params = useParams<{ runId: string }>();
  const [run, setRun] = useState<GenerationRun | null>(null);
  const [artifacts, setArtifacts] = useState<ArtifactList | null>(null);
  const [previews, setPreviews] = useState<TablePreview[]>([]);
  const [documentPreviews, setDocumentPreviews] = useState<DocumentPreview[]>([]);
  const [isLoading, setIsLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    async function loadRun() {
      const nextRun = await getRun(params.runId);
      const nextArtifacts = await getRunArtifacts(params.runId);
      const [nextPreviews, nextDocumentPreviews] =
        nextRun.kind === "document"
          ? [
              [],
              await Promise.all(
                nextRun.collections
                  .filter((collection) => collection.json_path)
                  .map((collection) =>
                    getDocumentPreview(nextRun.run_id, collection.collection_name, 10),
                  ),
              ),
            ]
          : [
              await Promise.all(
                nextRun.tables
                  .filter((table) => table.csv_path)
                  .map((table) => getTablePreview(nextRun.run_id, table.table_name, 10)),
              ),
              [],
            ];

      setRun(nextRun);
      setArtifacts(nextArtifacts);
      setPreviews(nextPreviews);
      setDocumentPreviews(nextDocumentPreviews);
    }

    loadRun()
      .catch((caughtError) => {
        setError(caughtError instanceof Error ? caughtError.message : "Unable to load run");
      })
      .finally(() => setIsLoading(false));
  }, [params.runId]);

  if (isLoading) {
    return <div className="h-96 animate-pulse rounded-lg border border-white/10 bg-white/[0.04]" />;
  }

  if (error || !run) {
    return (
      <>
        <Link
          href="/runs"
          className="mb-6 inline-flex items-center gap-2 text-sm font-semibold text-zinc-400 transition hover:text-white"
        >
          <ArrowLeft className="h-4 w-4" />
          Back to runs
        </Link>
        <EmptyState title="Run unavailable" detail={error ?? "The run could not be loaded."} />
      </>
    );
  }

  return (
    <>
      <Link
        href="/runs"
        className="mb-6 inline-flex items-center gap-2 text-sm font-semibold text-zinc-400 transition hover:text-white"
      >
        <ArrowLeft className="h-4 w-4" />
        Back to runs
      </Link>

      <PageHeader
        eyebrow="Run output"
        title="Generated data and artifacts."
        description="Preview generated tables or documents, then download files produced by the backend engine."
        action={
          <span
            className={`inline-flex items-center gap-2 rounded-md border px-3 py-2 text-xs font-semibold uppercase ${
              run.validation?.passed
                ? "border-emerald-300/30 bg-emerald-300/10 text-emerald-200"
                : "border-red-300/30 bg-red-300/10 text-red-200"
            }`}
          >
            {run.validation?.passed ? (
              <CheckCircle2 className="h-4 w-4" />
            ) : (
              <CircleAlert className="h-4 w-4" />
            )}
            {run.validation?.passed ? "Validation passed" : "Validation failed"}
          </span>
        }
      />

      <div className="grid gap-4 md:grid-cols-4">
        <StatTile label="Rows" value={String(run.total_rows)} hint="Generated by backend" />
        <StatTile
          label={run.kind === "document" ? "Collections" : "Tables"}
          value={String(run.table_count)}
          hint="Previewable below"
        />
        <StatTile label="Domain" value={run.domain} hint="Product generation profile" />
        <StatTile label="Formats" value={run.output_formats.join(" ")} hint="Downloadable artifacts" />
      </div>

      <section className="mt-8">
        <div className="mb-4 flex items-center justify-between gap-4">
          <h2 className="text-xl font-semibold text-white">
            {run.kind === "document" ? "Collections · top 10 documents" : "Tables · top 10 rows"}
          </h2>
          <p className="text-sm text-zinc-500">
            {run.kind === "document"
              ? "Document previews use MongoDB-style JSON cards."
              : "Collapsed by table so wide output stays readable."}
          </p>
        </div>
        {run.kind === "document" && documentPreviews.length > 0 ? (
          <div className="space-y-4">
            {documentPreviews.map((preview) => (
              <DocumentPreviewCards key={preview.collection_name} preview={preview} />
            ))}
          </div>
        ) : previews.length > 0 ? (
          <div className="space-y-3">
            {previews.map((preview, index) => (
              <PreviewTable
                key={preview.table_name}
                preview={preview}
                defaultOpen={index === 0}
              />
            ))}
          </div>
        ) : (
          <EmptyState
            title="No previews available"
            detail="Generate with previewable output enabled to inspect records."
          />
        )}
      </section>

      <section className="mt-8">
        <div className="mb-4 flex items-center justify-between gap-4">
          <h2 className="text-xl font-semibold text-white">Download data and reports</h2>
          <p className="text-sm text-zinc-500">Files come directly from the backend artifact API.</p>
        </div>
        <ArtifactButtons artifacts={artifacts} />
      </section>
    </>
  );
}

function DocumentPreviewCards({ preview }: { preview: DocumentPreview }) {
  return (
    <details className="rounded-lg border border-white/10 bg-white/[0.03] p-4" open>
      <summary className="cursor-pointer text-sm font-semibold text-white">
        {preview.collection_name} · top {preview.documents.length} documents
      </summary>
      <div className="mt-4 grid gap-3 xl:grid-cols-2">
        {preview.documents.map((document, index) => (
          <pre
            key={index}
            className="max-h-96 overflow-auto rounded-md border border-white/10 bg-black/30 p-4 text-xs leading-5 text-zinc-300"
          >
            {JSON.stringify(document, null, 2)}
          </pre>
        ))}
      </div>
    </details>
  );
}
