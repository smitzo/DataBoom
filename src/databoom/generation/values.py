"""Primitive value generation for planned columns."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import UTC, date, datetime, time, timedelta
from decimal import Decimal, InvalidOperation
from typing import Any
from uuid import UUID

from databoom.generation.domains import DomainProfile, DomainValueProvider, provider_for
from databoom.generation.plan import ColumnPlan, ColumnStrategy
from databoom.generation.seed import SeedManager
from databoom.schema.models import TypeFamily

type GeneratedValue = str | int | float | bool | datetime | dict[str, Any] | None


@dataclass(frozen=True)
class ValueGenerator:
    """Generate deterministic primitive values for column plans."""

    seed_manager: SeedManager
    domain: DomainProfile = DomainProfile.GENERAL
    null_probability: float = 0.0
    provider: DomainValueProvider = field(init=False)

    def __post_init__(self) -> None:
        if not 0 <= self.null_probability <= 1:
            raise ValueError("null probability must be between 0 and 1")
        object.__setattr__(self, "provider", provider_for(self.domain))

    def value_for(self, table_name: str, column: ColumnPlan, row_index: int) -> GeneratedValue:
        """Generate one type-compatible value for a table column and row index."""

        if row_index < 0:
            raise ValueError("row index cannot be negative")
        if column.strategy == ColumnStrategy.FOREIGN_KEY:
            raise ValueError("foreign-key values must be generated by the relationship solver")

        stream = self.seed_manager.stream(table_name, column.name, row_index)
        if column.nullable and column.strategy != ColumnStrategy.PRIMARY_KEY:
            if stream.random() < self._null_probability_for(column):
                return None

        if column.strategy == ColumnStrategy.PRIMARY_KEY:
            return self._primary_key_value(table_name, column, row_index)
        if (
            profiled_number := self._profiled_numeric_value(table_name, column, row_index)
        ) is not None:
            return profiled_number
        if (
            profiled_datetime := self._profiled_datetime_value(table_name, column, row_index)
        ) is not None:
            return profiled_datetime
        if (profiled_value := self._profiled_top_value(table_name, column, row_index)) is not None:
            return profiled_value
        return self._generated_value(table_name, column, row_index)

    def _primary_key_value(
        self,
        table_name: str,
        column: ColumnPlan,
        row_index: int,
    ) -> GeneratedValue:
        if column.type_family == TypeFamily.UUID:
            return self._uuid(table_name, column.name, row_index)
        if column.type_family == TypeFamily.STRING:
            return f"{_safe_name(table_name)}_{column.name}_{row_index + 1}"
        return row_index + 1

    def _generated_value(
        self,
        table_name: str,
        column: ColumnPlan,
        row_index: int,
    ) -> GeneratedValue:
        domain_value = self.provider.value_for(
            table_name=table_name,
            column_name=column.name,
            type_family=column.type_family,
            row_index=row_index,
            seed_manager=self.seed_manager,
        )
        if domain_value is not None:
            return domain_value

        stream = self.seed_manager.stream("value", table_name, column.name, row_index)

        match column.type_family:
            case TypeFamily.BOOLEAN:
                return bool(stream.getrandbits(1))
            case TypeFamily.DATETIME:
                return datetime(2024, 1, 1, tzinfo=UTC) + timedelta(
                    seconds=(row_index * 60) + stream.randint(0, 59)
                )
            case TypeFamily.JSON:
                return {"table": table_name, "column": column.name, "index": row_index + 1}
            case TypeFamily.NUMERIC:
                return stream.randint(1, 1_000_000)
            case TypeFamily.UUID:
                return self._uuid(table_name, column.name, row_index)
            case TypeFamily.STRING | TypeFamily.ENUM | TypeFamily.UNKNOWN:
                return self._string_value(table_name, column.name, row_index)

    def _string_value(self, table_name: str, column_name: str, row_index: int) -> str:
        stream = self.seed_manager.stream("string", table_name, column_name, row_index)
        normalized = column_name.lower()

        if "email" in normalized:
            token = stream.randint(10_000, 99_999)
            return f"user{row_index + 1}-{token}@example.test"
        if "phone" in normalized:
            return f"+1555{stream.randint(1000000, 9999999)}"
        if "name" in normalized:
            return f"{column_name.replace('_', ' ').title()} {row_index + 1}"
        if "status" in normalized:
            return ["active", "pending", "disabled"][stream.randint(0, 2)]

        token = stream.randint(10_000, 99_999)
        return f"{_safe_name(table_name)}_{column_name}_{row_index + 1}_{token}"

    def _null_probability_for(self, column: ColumnPlan) -> float:
        if column.profile_hint is None or column.profile_hint.sample_count == 0:
            return self.null_probability
        return column.profile_hint.null_rate

    def _profiled_top_value(
        self,
        table_name: str,
        column: ColumnPlan,
        row_index: int,
    ) -> str | None:
        hint = column.profile_hint
        if hint is None or not hint.top_values:
            return None
        if column.type_family not in {TypeFamily.STRING, TypeFamily.ENUM, TypeFamily.UNKNOWN}:
            return None

        top_value_count = sum(top_value.count for top_value in hint.top_values)
        if top_value_count <= 0:
            return None

        coverage = _top_value_coverage(hint.sample_count, hint.null_rate, top_value_count)
        if hint.distinct_count > len(hint.top_values):
            stream = self.seed_manager.stream(
                "profile-top-value-coverage",
                table_name,
                column.name,
                row_index,
            )
            if stream.random() > coverage:
                return None

        stream = self.seed_manager.stream("profile-top-value", table_name, column.name, row_index)
        selected = stream.randrange(top_value_count)
        cumulative = 0
        for top_value in hint.top_values:
            cumulative += top_value.count
            if selected < cumulative:
                return top_value.value
        return hint.top_values[-1].value

    def _profiled_numeric_value(
        self,
        table_name: str,
        column: ColumnPlan,
        row_index: int,
    ) -> int | float | None:
        hint = column.profile_hint
        if hint is None or column.type_family != TypeFamily.NUMERIC:
            return None
        if hint.min_value is None or hint.max_value is None:
            return None

        bounds = _numeric_bounds(hint.min_value, hint.max_value)
        if bounds is None:
            return None
        minimum, maximum = bounds
        if minimum == maximum:
            return _numeric_result(minimum, _decimal_places(minimum, maximum))

        stream = self.seed_manager.stream(
            "profile-numeric-range",
            table_name,
            column.name,
            row_index,
        )
        if _is_integral(minimum) and _is_integral(maximum):
            return stream.randint(int(minimum), int(maximum))

        try:
            value = stream.uniform(float(minimum), float(maximum))
        except OverflowError:
            return None
        return round(value, _decimal_places(minimum, maximum))

    def _profiled_datetime_value(
        self,
        table_name: str,
        column: ColumnPlan,
        row_index: int,
    ) -> datetime | None:
        hint = column.profile_hint
        if hint is None or column.type_family != TypeFamily.DATETIME:
            return None
        if hint.min_value is None or hint.max_value is None:
            return None

        bounds = _datetime_bounds(hint.min_value, hint.max_value)
        if bounds is None:
            return None
        minimum, maximum = bounds
        if minimum == maximum:
            return minimum

        total_seconds = (maximum - minimum).total_seconds()
        if total_seconds <= 0:
            return minimum

        stream = self.seed_manager.stream(
            "profile-datetime-range",
            table_name,
            column.name,
            row_index,
        )
        return minimum + timedelta(seconds=stream.uniform(0, total_seconds))

    def _uuid(self, table_name: str, column_name: str, row_index: int) -> str:
        stream = self.seed_manager.stream("uuid", table_name, column_name, row_index)
        return str(UUID(int=stream.getrandbits(128), version=4))


def _top_value_coverage(sample_count: int, null_rate: float, top_value_count: int) -> float:
    if sample_count <= 0:
        return 1.0
    non_null_sample_count = max(1, round(sample_count * (1 - null_rate)))
    return min(1.0, top_value_count / non_null_sample_count)


def _numeric_bounds(minimum: str, maximum: str) -> tuple[Decimal, Decimal] | None:
    parsed_minimum = _parse_decimal(minimum)
    parsed_maximum = _parse_decimal(maximum)
    if parsed_minimum is None or parsed_maximum is None:
        return None
    if parsed_minimum <= parsed_maximum:
        return parsed_minimum, parsed_maximum
    return parsed_maximum, parsed_minimum


def _parse_decimal(value: str) -> Decimal | None:
    try:
        parsed = Decimal(value.strip())
    except (InvalidOperation, ValueError):
        return None
    if not parsed.is_finite():
        return None
    return parsed


def _numeric_result(value: Decimal, decimal_places: int) -> int | float:
    if _is_integral(value):
        return int(value)
    return round(float(value), decimal_places)


def _is_integral(value: Decimal) -> bool:
    return value == value.to_integral_value()


def _decimal_places(*values: Decimal) -> int:
    return min(6, max(max(0, -value.as_tuple().exponent) for value in values))


def _datetime_bounds(minimum: str, maximum: str) -> tuple[datetime, datetime] | None:
    parsed_minimum = _parse_datetime(minimum)
    parsed_maximum = _parse_datetime(maximum)
    if parsed_minimum is None or parsed_maximum is None:
        return None
    if parsed_minimum <= parsed_maximum:
        return parsed_minimum, parsed_maximum
    return parsed_maximum, parsed_minimum


def _parse_datetime(value: str) -> datetime | None:
    normalized = _normalize_datetime_text(value)
    try:
        parsed = datetime.fromisoformat(normalized)
    except ValueError:
        try:
            parsed_date = date.fromisoformat(normalized)
        except ValueError:
            return None
        return datetime.combine(parsed_date, time.min, tzinfo=UTC)

    if parsed.tzinfo is None:
        return parsed.replace(tzinfo=UTC)
    return parsed.astimezone(UTC)


def _normalize_datetime_text(value: str) -> str:
    normalized = value.strip()
    if normalized.endswith("Z"):
        normalized = f"{normalized[:-1]}+00:00"
    if "T" in normalized or " " in normalized:
        normalized = re.sub(r"([+-]\d{2})$", r"\1:00", normalized)
    return normalized


def _safe_name(value: str) -> str:
    return value.replace(".", "_").replace("-", "_")
