"""Primitive value generation for planned columns."""

from __future__ import annotations

from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from typing import Any
from uuid import UUID

from boom_data.generation.plan import ColumnPlan, ColumnStrategy
from boom_data.generation.seed import SeedManager
from boom_data.schema.models import TypeFamily

type GeneratedValue = str | int | float | bool | datetime | dict[str, Any] | None


@dataclass(frozen=True)
class ValueGenerator:
    """Generate deterministic primitive values for column plans."""

    seed_manager: SeedManager
    null_probability: float = 0.0

    def __post_init__(self) -> None:
        if not 0 <= self.null_probability <= 1:
            raise ValueError("null probability must be between 0 and 1")

    def value_for(self, table_name: str, column: ColumnPlan, row_index: int) -> GeneratedValue:
        """Generate one type-compatible value for a table column and row index."""

        if row_index < 0:
            raise ValueError("row index cannot be negative")
        if column.strategy == ColumnStrategy.FOREIGN_KEY:
            raise ValueError("foreign-key values must be generated by the relationship solver")

        stream = self.seed_manager.stream(table_name, column.name, row_index)
        if column.nullable and column.strategy != ColumnStrategy.PRIMARY_KEY:
            if stream.random() < self.null_probability:
                return None

        if column.strategy == ColumnStrategy.PRIMARY_KEY:
            return self._primary_key_value(table_name, column, row_index)
        return self._generated_value(table_name, column, row_index)

    def _primary_key_value(
        self,
        table_name: str,
        column: ColumnPlan,
        row_index: int,
    ) -> GeneratedValue:
        if column.type_family == TypeFamily.UUID:
            return self._uuid(table_name, column.name, row_index)
        if column.type_family == TypeFamily.STRING:
            return f"{_safe_name(table_name)}_{column.name}_{row_index + 1}"
        return row_index + 1

    def _generated_value(
        self,
        table_name: str,
        column: ColumnPlan,
        row_index: int,
    ) -> GeneratedValue:
        stream = self.seed_manager.stream("value", table_name, column.name, row_index)

        match column.type_family:
            case TypeFamily.BOOLEAN:
                return bool(stream.getrandbits(1))
            case TypeFamily.DATETIME:
                return datetime(2024, 1, 1, tzinfo=UTC) + timedelta(
                    seconds=(row_index * 60) + stream.randint(0, 59)
                )
            case TypeFamily.JSON:
                return {"table": table_name, "column": column.name, "index": row_index + 1}
            case TypeFamily.NUMERIC:
                return stream.randint(1, 1_000_000)
            case TypeFamily.UUID:
                return self._uuid(table_name, column.name, row_index)
            case TypeFamily.STRING | TypeFamily.ENUM | TypeFamily.UNKNOWN:
                return self._string_value(table_name, column.name, row_index)

    def _string_value(self, table_name: str, column_name: str, row_index: int) -> str:
        stream = self.seed_manager.stream("string", table_name, column_name, row_index)
        normalized = column_name.lower()

        if "email" in normalized:
            token = stream.randint(10_000, 99_999)
            return f"user{row_index + 1}-{token}@example.test"
        if "phone" in normalized:
            return f"+1555{stream.randint(1000000, 9999999)}"
        if "name" in normalized:
            return f"{column_name.replace('_', ' ').title()} {row_index + 1}"
        if "status" in normalized:
            return ["active", "pending", "disabled"][stream.randint(0, 2)]

        token = stream.randint(10_000, 99_999)
        return f"{_safe_name(table_name)}_{column_name}_{row_index + 1}_{token}"

    def _uuid(self, table_name: str, column_name: str, row_index: int) -> str:
        stream = self.seed_manager.stream("uuid", table_name, column_name, row_index)
        return str(UUID(int=stream.getrandbits(128), version=4))


def _safe_name(value: str) -> str:
    return value.replace(".", "_").replace("-", "_")
